class Applier:
    def __init__(self, afd: int):
        self.afd = afd
        limit = os.environ.get("SOLAR_CODEX_AGENTS_TEST_FAIL_AFTER")
        self.limit = int(limit) if limit not in (None, "") else None
        self.count = 0
        self.seq = 0

    def _tick(self):
        if self.limit is not None and self.count >= self.limit:
            raise InjectedFailure(f"injected failure after {self.count} operations")
        self.count += 1

    def write(self, name: str, data: bytes):
        self._tick()
        self.seq += 1
        tmp = f"{TMP_PREFIX}{os.getpid()}-{self.seq}"
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW
                     | getattr(os, "O_CLOEXEC", 0), 0o644, dir_fd=self.afd)
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp, name, src_dir_fd=self.afd, dst_dir_fd=self.afd)
        except BaseException:
            try:
                os.unlink(tmp, dir_fd=self.afd)
            except OSError:
                pass
            raise
        os.fsync(self.afd)

    def delete(self, name: str):
        self._tick()
        try:
            os.unlink(name, dir_fd=self.afd)
        except FileNotFoundError:
            pass
        os.fsync(self.afd)


def acquire_lock(afd: int):
    try:
        timeout = float(os.environ.get("SOLAR_CODEX_AGENTS_LOCK_TIMEOUT", "30"))
    except ValueError:
        timeout = 30.0
    deadline = time.monotonic() + timeout
    while True:
        try:
            fcntl.flock(afd, fcntl.LOCK_EX | fcntl.LOCK_NB)
            return True
        except OSError as exc:
            if exc.errno not in (errno.EWOULDBLOCK, errno.EAGAIN, errno.EACCES):
                raise
        if time.monotonic() >= deadline:
            return False
        time.sleep(0.05)


def apply_plan(plan: Plan, dest: Dest, afd: int) -> None:
    final_bytes = manifest_bytes(plan.final_entries)
    ap = Applier(afd)
    if not plan.has_file_ops:
        if dest.manifest_bytes != final_bytes and (dest.manifest_bytes is not None or plan.final_entries):
            ap.write(MANIFEST_NAME, final_bytes)
        return
    ap.write(MANIFEST_NAME, manifest_bytes(plan.transitional_entries))
    for item, _previous in plan.writes:
        ap.write(item.file, item.data)
    for entry in plan.deletes:
        ap.delete(entry["file"])
    ap.write(MANIFEST_NAME, final_bytes)


