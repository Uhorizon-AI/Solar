@dataclass
class Dest:
    entries: dict = field(default_factory=dict)        # name -> kind
    manifest_bytes: bytes | None = None
    manifest: list = field(default_factory=list)       # validated entries
    foreign_names: set = field(default_factory=set)    # casefolded
    foreign_text: list = field(default_factory=list)
    config_names: set = field(default_factory=set)     # casefolded
    contents: dict = field(default_factory=dict)       # name -> bytes for managed candidates
    stale_tmp: list = field(default_factory=list)


def validate_manifest(raw: bytes) -> list:
    def bad(msg):
        raise Refusal(f"corrupt {MANIFEST_NAME}: {msg}")
    try:
        data = json.loads(raw.decode("utf-8"))
    except (ValueError, UnicodeDecodeError) as exc:
        bad(str(exc))
    if not isinstance(data, dict) or set(data) != {"format", "generator", "agents"}:
        bad("unexpected top-level keys")
    if data["format"] != 1 or data["generator"] != MANIFEST_GENERATOR:
        bad("unexpected format or generator")
    if not isinstance(data["agents"], list):
        bad("agents must be an array")
    required = {"source", "identity", "source_sha256", "name", "file", "sha256"}
    optional = {"previous_sha256", "retiring"}
    seen = {"file": set(), "name": set(), "source": set(), "identity": set()}
    entries = []
    for entry in data["agents"]:
        if not isinstance(entry, dict):
            bad("entry is not an object")
        keys = set(entry)
        if not required <= keys or keys - required - optional:
            bad("entry has missing or unknown keys")
        for key in ("source", "identity", "name", "file"):
            if not isinstance(entry[key], str):
                bad(f"{key} must be a string")
        for key in ("source_sha256", "sha256"):
            if not isinstance(entry[key], str) or not HEX64.fullmatch(entry[key]):
                bad(f"{key} must be a sha256 hex digest")
        if "previous_sha256" in entry and entry["previous_sha256"] is not None and (
                not isinstance(entry["previous_sha256"], str) or not HEX64.fullmatch(entry["previous_sha256"])):
            bad("previous_sha256 must be a sha256 hex digest or null")
        if "retiring" in entry and entry["retiring"] is not True:
            bad("retiring must be true when present")
        match = SOURCE_RE.fullmatch(entry["source"])
        if not match or entry["identity"] != f"{match.group(1)}:{match.group(2)}":
            bad("source and identity do not agree")
        if not PUBLIC_NAME_RE.fullmatch(entry["name"]) or len(entry["name"]) > MAX_NAME_LEN:
            bad("name is not a valid public name")
        if entry["file"] != entry["name"] + ".toml":
            bad("file does not match name")
        try:
            expected = public_name(match.group(1), match.group(2))
        except ContractError:
            bad("identity cannot produce a public name")
        if expected != entry["name"]:
            bad("name does not derive from identity")
        for key in seen:
            if entry[key] in seen[key]:
                bad(f"duplicate {key}")
            seen[key].add(entry[key])
        entries.append(entry)
    return entries


def _kind(entry: os.DirEntry) -> str:
    if entry.is_symlink():
        return "symlink"
    if entry.is_file(follow_symlinks=False):
        return "file"
    if entry.is_dir(follow_symlinks=False):
        return "dir"
    return "other"


def open_codex_dir(workspace: Path, create: bool):
    """Return (codex_fd, agents_fd), either may be None when absent.

    Refuses when .codex or .codex/agents is a symlink or not a directory.
    """
    dflags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0)
    try:
        cfd = os.open(workspace / ".codex", dflags)
    except FileNotFoundError:
        if not create:
            return None, None
        try:
            os.mkdir(workspace / ".codex", 0o755)
        except FileExistsError:
            pass
        cfd = _open_dir_checked(workspace / ".codex", dflags)
    except OSError:
        raise Refusal(".codex is a symlink or not a directory; refusing to write through it")
    try:
        try:
            afd = os.open("agents", dflags, dir_fd=cfd)
        except FileNotFoundError:
            if not create:
                return cfd, None
            try:
                os.mkdir("agents", 0o755, dir_fd=cfd)
            except FileExistsError:
                pass
            afd = os.open("agents", dflags, dir_fd=cfd)
        except OSError:
            raise Refusal(".codex/agents is a symlink or not a directory; refusing to write through it")
    except BaseException:
        os.close(cfd)
        raise
    return cfd, afd


def _open_dir_checked(path, dflags):
    try:
        return os.open(path, dflags)
    except OSError:
        raise Refusal(".codex is a symlink or not a directory; refusing to write through it")


def _toml_agent_names(text: str) -> set:
    names = set()
    try:
        parsed = tomllib.loads(text)
        agents = parsed.get("agents")
        if isinstance(agents, dict):
            names.update(k.casefold() for k, v in agents.items() if isinstance(v, dict))
        return names
    except Exception:
        pass
    for match in re.finditer(r'^\s*\[agents\.(?:"([^"]+)"|([A-Za-z0-9_-]+))\]', text, re.M):
        names.add((match.group(1) or match.group(2)).casefold())
    return names


def read_dest(workspace: Path, cfd, afd) -> Dest:
    dest = Dest()
    if cfd is not None:
        try:
            raw = _read_regular("config.toml", MAX_DEST_READ, dir_fd=cfd)
            dest.config_names = _toml_agent_names(raw.decode("utf-8", "replace"))
        except (OSError, ContractError):
            pass
    if afd is None:
        return dest
    with os.scandir(afd) as it:
        for entry in it:
            dest.entries[entry.name] = _kind(entry)
    if MANIFEST_NAME in dest.entries:
        if dest.entries[MANIFEST_NAME] != "file":
            raise Refusal(f"{MANIFEST_NAME} is not a regular file")
        try:
            dest.manifest_bytes = _read_regular(MANIFEST_NAME, MAX_DEST_READ, dir_fd=afd)
        except (OSError, ContractError) as exc:
            raise Refusal(f"cannot read {MANIFEST_NAME}: {exc}")
        dest.manifest = validate_manifest(dest.manifest_bytes)
    managed = {e["file"] for e in dest.manifest}
    for name, kind in sorted(dest.entries.items()):
        if name.startswith(TMP_PREFIX):
            dest.stale_tmp.append(name)
            continue
        if kind != "file":
            continue
        is_toml = name.lower().endswith(".toml")
        if not is_toml and name not in managed:
            continue
        try:
            raw = _read_regular(name, MAX_DEST_READ, dir_fd=afd)
        except (OSError, ContractError):
            raw = None
        if name in managed:
            dest.contents[name] = raw
            continue
        dest.contents[name] = raw
        dest.foreign_names.add(name[:-5].casefold())
        if raw is None:
            continue
        text = raw.decode("utf-8", "replace")
        dest.foreign_text.append(text)
        try:
            parsed_name = tomllib.loads(text).get("name")
        except Exception:
            match = re.search(r'^\s*name\s*=\s*"([^"\n]*)"', text, re.M)
            parsed_name = match.group(1) if match else None
        if isinstance(parsed_name, str):
            dest.foreign_names.add(parsed_name.casefold())
    # Managed candidates that are not .toml names cannot exist (validated), but
    # also read unmanaged files that case-collide with a managed target.
    for entry in dest.manifest:
        if entry["file"] in dest.entries and entry["file"] not in dest.contents:
            dest.contents[entry["file"]] = None
    return dest


