@dataclass
class Eligible:
    planet: str
    agent: str
    source: str
    identity: str
    name: str
    file: str
    source_sha: str
    data: bytes
    description: str
    instructions: str


@dataclass
class Scan:
    planets_missing: bool = False
    eligible: list = field(default_factory=list)
    omitted: list = field(default_factory=list)       # (source, reason)
    unknown_sources: set = field(default_factory=set)
    invalid_sources: set = field(default_factory=set)  # contract exists but does not validate
    unknown_planets: set = field(default_factory=set)  # exact planet names
    # Presence facts used to prove a source disappeared before adopting its entry
    # on a rename: present_sources = every .md listed (valid or not);
    # scanned_planets = planets whose agents/ dir was actually listed;
    # listed_planets = every entry name under planets/.
    present_sources: set = field(default_factory=set)
    scanned_planets: set = field(default_factory=set)
    listed_planets: set = field(default_factory=set)
    excluded_planets: set = field(default_factory=set)  # casefolded planet keys


def list_planet_entries(workspace: Path):
    """Names under planets/ and None if it is missing. Never stats entries."""
    planets = workspace / "planets"
    try:
        with os.scandir(planets) as it:
            return sorted(entry.name for entry in it)
    except FileNotFoundError:
        return None
    except NotADirectoryError:
        return None
    except OSError as exc:
        raise Refusal(f"cannot list planets/: {exc.strerror or exc}")


def _read_regular(path: str, limit: int, dir_fd=None) -> bytes:
    flags = os.O_RDONLY | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NONBLOCK", 0)
    fd = os.open(path, flags, dir_fd=dir_fd) if dir_fd is not None else os.open(path, flags)
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise ContractError("unsafe link or not a regular file")
        chunks, total = [], 0
        while True:
            chunk = os.read(fd, 65536)
            if not chunk:
                break
            chunks.append(chunk)
            total += len(chunk)
            if total > limit:
                break
        return b"".join(chunks)
    finally:
        os.close(fd)


def scan_sources(workspace: Path, cfg: Config) -> Scan:
    scan = Scan()
    names = list_planet_entries(workspace)
    if names is None:
        scan.planets_missing = True
        return scan
    scan.listed_planets = set(names)
    planets_dir = workspace / "planets"
    planets_real = os.path.realpath(planets_dir)
    excluded = excluded_planet_map(cfg)
    scan.excluded_planets = set(excluded)
    excluded_ids = excluded_agent_keys(cfg)
    excluded_names = [name for name in sorted(set(cfg.exclude_planets) | set(cfg.global_exclude_planets))]
    patterns = {name: reference_patterns(name) for name in excluded_names}

    for pname in names:
        if pname.startswith(".") or planet_key(pname) in excluded:
            continue  # excluded planets and hidden entries are never touched
        ppath = planets_dir / pname
        try:
            lst = os.lstat(ppath)
        except OSError:
            scan.unknown_planets.add(pname)
            scan.omitted.append((f"planets/{pname}", "cannot inspect planet"))
            continue
        if stat.S_ISLNK(lst.st_mode):
            real = os.path.realpath(ppath)
            same_tree = os.path.dirname(real) == planets_real
            if not same_tree or planet_key(os.path.basename(real)) in excluded or not os.path.isdir(real):
                scan.unknown_planets.add(pname)
                scan.omitted.append((f"planets/{pname}", "unsafe link (planet link leaves planets/ or targets an excluded planet)"))
                continue
        elif not stat.S_ISDIR(lst.st_mode):
            continue
        if not ID_RE.fullmatch(pname):
            scan.omitted.append((f"planets/{pname}", "planet name has unsupported characters"))
            continue
        agents_dir = ppath / "agents"
        try:
            alst = os.lstat(agents_dir)
        except FileNotFoundError:
            continue
        except OSError as exc:
            raise Refusal(f"cannot inspect planets/{pname}/agents: {exc.strerror or exc}")
        if stat.S_ISLNK(alst.st_mode):
            scan.unknown_planets.add(pname)
            scan.omitted.append((f"planets/{pname}/agents", "unsafe link"))
            continue
        if not stat.S_ISDIR(alst.st_mode):
            continue
        try:
            with os.scandir(agents_dir) as it:
                entries = sorted(e.name for e in it)
        except OSError as exc:
            raise Refusal(f"cannot list planets/{pname}/agents: {exc.strerror or exc}")
        scan.scanned_planets.add(pname)
        for fname in entries:
            if fname.lower() == "readme.md" or fname.startswith((".", "_")) or not fname.endswith(".md"):
                continue
            stem = fname[:-3]
            source = f"planets/{pname}/agents/{fname}"
            scan.present_sources.add(source)
            if agent_key(pname, stem) in excluded_ids:
                scan.omitted.append((source, "excluded by identity"))
                continue
            if not AGENT_NAME_RE.fullmatch(stem):
                scan.omitted.append((source, "file name is not a valid agent name"))
                continue
            try:
                elst = os.lstat(agents_dir / fname)
            except OSError:
                scan.unknown_sources.add(source)
                scan.omitted.append((source, "cannot inspect file"))
                continue
            if not stat.S_ISREG(elst.st_mode):
                scan.omitted.append((source, "unsafe link or not a regular file"))
                scan.invalid_sources.add(source)
                continue
            try:
                raw = _read_regular(str(agents_dir / fname), MAX_SOURCE_BYTES)
            except ContractError as exc:
                scan.omitted.append((source, str(exc)))
                scan.invalid_sources.add(source)
                continue
            except OSError as exc:
                if exc.errno == errno.ELOOP:
                    scan.omitted.append((source, "unsafe link or not a regular file"))
                    scan.invalid_sources.add(source)
                else:
                    scan.unknown_sources.add(source)
                    scan.omitted.append((source, f"unreadable: {exc.strerror or exc}"))
                continue
            try:
                contract = parse_contract(pname, stem, raw)
                name = public_name(pname, stem)
            except ContractError as exc:
                scan.omitted.append((source, str(exc)))
                scan.invalid_sources.add(source)
                continue
            hit = None
            for ex_name, pats in patterns.items():
                if any(p.search(contract.text) for p in pats):
                    hit = ex_name
                    break
            if hit is not None:
                scan.omitted.append((source, f"references excluded planet {hit}"))
                continue
            text, instructions = render_agent(
                pname, stem, name, contract.description, contract.body, contract.source_sha)
            if not verify_generated(text, name, contract.description, instructions):
                scan.omitted.append((source, "serialization failed"))
                scan.invalid_sources.add(source)
                continue
            scan.eligible.append(Eligible(
                pname, stem, source, f"{pname}:{stem}", name, f"{name}.toml",
                contract.source_sha, text.encode("utf-8"), contract.description, instructions))
    return scan


