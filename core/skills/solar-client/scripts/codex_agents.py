@dataclass
class Config:
    enabled: bool = False
    exclude_planets: list = field(default_factory=list)
    exclude_agents: list = field(default_factory=list)
    global_exclude_planets: list = field(default_factory=list)
    data: dict = field(default_factory=dict)
    read_path: str = ""


def settings_read_path(workspace: Path) -> Path:
    path = workspace / ".solar/settings.json"
    if not path.is_file():
        legacy = workspace / ".solar/manifest.json"
        if legacy.is_file():
            return legacy
    return path


def _validate_id_list(value, key: str, pattern: re.Pattern, what: str) -> list:
    if not isinstance(value, list):
        raise Usage(f"{key} must be an array of {what}")
    for item in value:
        if not isinstance(item, str) or not pattern.fullmatch(item):
            raise Usage(f"invalid entry in {key}: {item!r}")
    return list(value)


def load_config(workspace: Path) -> Config:
    path = settings_read_path(workspace)
    data: dict = {}
    if path.is_file():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise Usage(f"invalid Solar workspace settings: {path}: {exc}")
        if not isinstance(data, dict):
            raise Usage(f"Solar workspace settings must be a JSON object: {path}")
    cfg = Config(data=data, read_path=str(path))
    cfg.global_exclude_planets = _validate_id_list(
        data.get("sync_exclude_planets", []), "sync_exclude_planets", GLOBAL_ID_RE, "planet names")
    if "codex_agents" in data:
        block = data["codex_agents"]
        if not isinstance(block, dict):
            raise Usage("codex_agents must be an object")
        unknown = sorted(set(block) - SETTINGS_KEYS)
        if unknown:
            raise Usage(f"unknown key(s) in codex_agents: {', '.join(unknown)}")
        if "enabled" in block:
            if not isinstance(block["enabled"], bool):
                raise Usage("codex_agents.enabled must be a boolean")
            cfg.enabled = block["enabled"]
        cfg.exclude_planets = _validate_id_list(
            block.get("exclude_planets", []), "codex_agents.exclude_planets", ID_RE, "planet ids")
        cfg.exclude_agents = _validate_id_list(
            block.get("exclude_agents", []), "codex_agents.exclude_agents", IDENTITY_RE,
            "planet:agent identities")
    return cfg


def write_config(workspace: Path, cfg: Config) -> None:
    """Atomic write of the codex_agents block, preserving every other key."""
    write_path = workspace / ".solar/settings.json"
    data = dict(cfg.data)
    data["codex_agents"] = {
        "enabled": cfg.enabled,
        "exclude_planets": list(cfg.exclude_planets),
        "exclude_agents": list(cfg.exclude_agents),
    }
    data["scope"] = SOLAR_SCOPE
    data["layout"] = SOLAR_LAYOUT
    os.makedirs(write_path.parent, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".settings.", suffix=".json", dir=write_path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=2)
            fh.write("\n")
        os.replace(tmp, write_path)
    except Exception:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    legacy = write_path.parent / "manifest.json"
    if legacy.is_file() and os.path.realpath(legacy) != os.path.realpath(write_path):
        os.unlink(legacy)


def planet_key(name: str) -> str:
    return name.casefold()


def agent_key(planet: str, agent: str) -> tuple:
    return (planet.casefold(), agent.casefold().replace("-", "_"))


def excluded_planet_map(cfg: Config) -> dict:
    """casefolded planet -> 'global' | 'codex' (global wins)."""
    result: dict = {}
    for name in cfg.exclude_planets:
        result[planet_key(name)] = "codex"
    for name in cfg.global_exclude_planets:
        result[planet_key(name)] = "global"
    return result


def excluded_agent_keys(cfg: Config) -> set:
    keys = set()
    for ident in cfg.exclude_agents:
        match = IDENTITY_RE.fullmatch(ident)
        if match:
            keys.add(agent_key(match.group(1), match.group(2)))
    return keys


# --------------------------------------------------------------------------
# TOML serialization
# --------------------------------------------------------------------------

_SIMPLE_ESCAPES = {"\\": "\\\\", "\b": "\\b", "\t": "\\t", "\f": "\\f", "\r": "\\r"}


def _escape_char(ch: str) -> str:
    if ch in _SIMPLE_ESCAPES:
        return _SIMPLE_ESCAPES[ch]
    code = ord(ch)
    if code < 0x20 or code == 0x7F:
        return f"\\u{code:04X}"
    return ch


def toml_basic_string(value: str) -> str:
    """Single-line TOML basic string."""
    out = []
    for ch in value:
        if ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(_escape_char(ch))
    return '"' + "".join(out) + '"'


def toml_multiline_string(value: str) -> str:
    """Multi-line TOML basic string (CRLF and CR are normalized to LF)."""
    value = value.replace("\r\n", "\n").replace("\r", "\n")
    out = []
    i, n = 0, len(value)
    while i < n:
        ch = value[i]
        if ch == '"':
            j = i
            while j < n and value[j] == '"':
                j += 1
            run = j - i
            if run >= 3 or j == n:
                out.append('\\"' * run)
            else:
                out.append('"' * run)
            i = j
            continue
        out.append("\n" if ch == "\n" else _escape_char(ch))
        i += 1
    return '"""\n' + "".join(out) + '"""'


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


WRAPPER = """\
This role is a derived copy of a Solar agent contract. Solar Client generated it from {source} (sha256 {sha}). It is not the editable source.

Before acting:
- Resolve every path from the workspace root.
- Read the current governance of the workspace (AGENTS.md at the workspace root) and of the planet (planets/{planet}/AGENTS.md) when they exist.
- If the source contract, or any source it requires, is missing, unreadable or in conflict, stop and report it instead of improvising.
- If the current source differs from the copy embedded below, the source prevails; tell the user to run `solar client sync`.

This role grants no authority to execute, send, schedule or change permissions. The task must carry the authorized object, scope and effect.

---

"""


def render_agent(planet: str, agent: str, name: str, description: str,
                 body: str, source_sha: str) -> str:
    source = f"planets/{planet}/agents/{agent}.md"
    instructions = WRAPPER.format(source=source, sha=source_sha, planet=planet)
    body = body.replace("\r\n", "\n").replace("\r", "\n").rstrip("\n") + "\n"
    instructions += body
    return (
        f"{MARK_LINE}\n"
        f"{SOURCE_LINE_PREFIX}{source} identity: {planet}:{agent} source_sha256: {source_sha}\n"
        f"name = {toml_basic_string(name)}\n"
        f"description = {toml_basic_string(description)}\n"
        f"developer_instructions = {toml_multiline_string(instructions)}\n"
    ), instructions


def verify_generated(text: str, name: str, description: str, instructions: str) -> bool:
    try:
        parsed = tomllib.loads(text)
    except Exception:
        return False
    return (set(parsed) == {"name", "description", "developer_instructions"}
            and parsed["name"] == name
            and parsed["description"] == description
            and parsed["developer_instructions"] == instructions)


def has_generation_mark(data: bytes) -> bool:
    try:
        lines = data.decode("utf-8").split("\n", 2)
    except UnicodeDecodeError:
        return False
    return (len(lines) >= 2 and lines[0] == MARK_LINE
            and lines[1].startswith(SOURCE_LINE_PREFIX))


def parsed_toml_name(data: bytes):
    try:
        parsed = tomllib.loads(data.decode("utf-8"))
    except Exception:
        return None
    name = parsed.get("name")
    return name if isinstance(name, str) else None


