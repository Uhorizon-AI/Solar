#!/usr/bin/env python3
"""Opt-in publisher of native Codex agents derived from planet agent contracts.

Reads ``planets/<planet>/agents/<agent>.md`` and writes derived roles to
``<workspace>/.codex/agents/solar__<planet>__<agent>.toml``. Publication is OFF
by default and never touches a planet that is excluded. Standard library only;
Python >= 3.11 is required to publish (generated TOML is round-tripped through
``tomllib`` before it is written).

Exit codes:
  0  ok
  2  usage error or invalid settings
  3  finished, but some agents were left untouched because of conflicts
  4  lock timeout (nothing changed)
  5  refusal before any write (corrupt manifest, unsafe destination, ...)
"""
from __future__ import annotations

import argparse
import errno
import fcntl
import hashlib
import json
import os
import re
import stat
import sys
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path

try:  # Python >= 3.11
    import tomllib
except ImportError:  # pragma: no cover - exercised only on old interpreters
    tomllib = None  # type: ignore[assignment]

EXIT_OK, EXIT_USAGE, EXIT_CONFLICT, EXIT_LOCK, EXIT_REFUSED = 0, 2, 3, 4, 5

ID_RE = re.compile(r"[A-Za-z0-9_.-]+\Z")
GLOBAL_ID_RE = re.compile(r"[A-Za-z0-9_.-]+(?::[A-Za-z0-9_.-]+)?\Z")
IDENTITY_RE = re.compile(r"([A-Za-z0-9_.-]+):([A-Za-z0-9_.-]+)\Z")
AGENT_NAME_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]*\Z")
COMPONENT_RE = re.compile(r"[a-z0-9]+(_[a-z0-9]+)*\Z")
PUBLIC_NAME_RE = re.compile(r"solar__[a-z0-9]+(_[a-z0-9]+)*__[a-z0-9]+(_[a-z0-9]+)*\Z")
SOURCE_RE = re.compile(r"planets/([A-Za-z0-9_.-]+)/agents/([A-Za-z0-9][A-Za-z0-9_-]*)\.md\Z")
HEX64 = re.compile(r"[0-9a-f]{64}\Z")

MAX_SOURCE_BYTES = 256 * 1024
MAX_DEST_READ = 4 * 1024 * 1024
MAX_NAME_LEN = 96
MAX_DESCRIPTION = 1024

MANIFEST_NAME = ".solar-managed.json"
MANIFEST_GENERATOR = "solar-client-codex-agents"
TMP_PREFIX = ".solar-tmp-"
MARK_LINE = ("# solar-client codex-agent v1 - generated by solar client sync; "
             "do not edit (edited files are reported and never overwritten)")
SOURCE_LINE_PREFIX = "# source: "

SETTINGS_KEYS = {"enabled", "exclude_planets", "exclude_agents"}

# Canonical layout/scope written into .solar/settings.json. Keep in sync with the
# writers in client_lib.sh (solar_client_write_settings_v12 and friends); this is
# the single literal for this script so a layout migration touches one place.
SOLAR_LAYOUT = "solar-client-v1.2"
SOLAR_SCOPE = "workspace"


class Usage(Exception):
    """Invalid usage or settings (exit 2)."""


class Refusal(Exception):
    """Refusal before any write (exit 5)."""


class InjectedFailure(RuntimeError):
    """Raised by the SOLAR_CODEX_AGENTS_TEST_FAIL_AFTER test hook."""


