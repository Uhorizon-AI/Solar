# Contract parsing
# --------------------------------------------------------------------------

class ContractError(Exception):
    pass


_KEY_RE = re.compile(r"([A-Za-z_][A-Za-z0-9_-]*):(?:[ \t]+(.*))?\Z")


def _dedent_block(lines: list) -> list:
    indents = [len(l) - len(l.lstrip()) for l in lines if l.strip()]
    cut = min(indents) if indents else 0
    return [l[cut:] if l.strip() else "" for l in lines]


def _scalar(raw, cont: list) -> str:
    raw = (raw or "").strip()
    if raw and raw[0] in ">|":
        if not re.fullmatch(r"[>|][+\-0-9]*", raw):
            raise ContractError("unsupported block scalar header")
        block = _dedent_block(cont)
        return ("\n" if raw[0] == "|" else " ").join(block)
    if raw.startswith('"'):
        if any(l.strip() for l in cont):
            raise ContractError("multi-line quoted scalars are not supported")
        try:
            value = json.loads(raw)
        except ValueError:
            raise ContractError("unsupported double-quoted scalar")
        if not isinstance(value, str):
            raise ContractError("unsupported double-quoted scalar")
        return value
    if raw.startswith("'"):
        if any(l.strip() for l in cont):
            raise ContractError("multi-line quoted scalars are not supported")
        if len(raw) < 2 or not raw.endswith("'") or "'" in raw[1:-1].replace("''", ""):
            raise ContractError("unsupported single-quoted scalar")
        return raw[1:-1].replace("''", "'")
    if raw and raw[0] in "[{&*!%@`":
        raise ContractError("unsupported scalar value")
    raw = re.sub(r"\s+#.*\Z", "", raw)
    parts = [raw] if raw else []
    parts += [l.strip() for l in cont if l.strip()]
    return " ".join(parts)


def parse_frontmatter(block: str) -> dict:
    entries: list = []
    seen = set()
    for line in block.split("\n"):
        if not line.strip():
            if entries:
                entries[-1][2].append("")
            continue
        if line[0] in " \t" or line.startswith("- "):
            if not entries:
                raise ContractError("indented frontmatter line before any key")
            entries[-1][2].append(line)
            continue
        if line.startswith("#"):
            continue
        match = _KEY_RE.match(line)
        if not match:
            raise ContractError("unsupported frontmatter line")
        key = match.group(1)
        if key in seen:
            raise ContractError(f"duplicate frontmatter key: {key}")
        seen.add(key)
        entries.append([key, match.group(2), []])
    result = {}
    for key, raw, cont in entries:
        if key in ("name", "description"):
            result[key] = _scalar(raw, cont)
    return result


@dataclass
class Contract:
    planet: str
    agent: str
    description: str
    body: str
    text: str
    source_sha: str


def parse_contract(planet: str, stem: str, raw: bytes) -> Contract:
    """Parse and validate a contract; raise ContractError with a specific reason."""
    if len(raw) > MAX_SOURCE_BYTES:
        raise ContractError("larger than 256 KiB")
    if b"\x00" in raw:
        raise ContractError("contains NUL bytes")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        raise ContractError("not valid UTF-8")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if not text.startswith("---\n"):
        raise ContractError("no frontmatter")
    rest = text[4:]
    if rest.startswith("---\n"):
        block, body = "", rest[4:]
    else:
        idx = rest.find("\n---\n")
        if idx < 0:
            raise ContractError("unclosed frontmatter")
        block, body = rest[:idx], rest[idx + 5:]
    meta = parse_frontmatter(block)
    name = meta.get("name", "")
    if not name:
        raise ContractError("frontmatter has no name")
    if not AGENT_NAME_RE.fullmatch(name):
        raise ContractError("name has unsupported characters")
    if name != stem:
        raise ContractError("name does not match the file name")
    description = " ".join(meta.get("description", "").split())
    if not description:
        raise ContractError("frontmatter has no description")
    if len(description) > MAX_DESCRIPTION:
        raise ContractError("description longer than 1024 characters")
    if not body.strip():
        raise ContractError("empty body")
    return Contract(planet, stem, description, body, text, sha256_hex(raw))


def public_name(planet: str, agent: str) -> str:
    comps = []
    for part in (planet, agent):
        comp = part.lower().replace("-", "_")
        if not COMPONENT_RE.fullmatch(comp):
            raise ContractError("name cannot be represented as a public agent name")
        comps.append(comp)
    name = f"solar__{comps[0]}__{comps[1]}"
    if len(name) > MAX_NAME_LEN:
        raise ContractError("public name longer than 96 characters")
    return name


def reference_patterns(planet: str) -> list:
    p = re.escape(planet)
    flags = re.IGNORECASE
    return [
        re.compile(rf"planets/{p}(?![A-Za-z0-9_.-])", flags),
        re.compile(rf"\.\./{p}/", flags),
        re.compile(rf"(?<![A-Za-z0-9_.:/-]){p}:[A-Za-z0-9_.-]+", flags),
    ]


