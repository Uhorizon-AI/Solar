def report(plan: Plan, as_json: bool = False, dry_run: bool = False, enabled: bool = True) -> None:
    if as_json:
        print(json.dumps({
            "mode": "contents",
            "enabled": enabled,
            "items": plan.items,
            "omitted": [{"source": s, "reason": r} for s, r in plan.omitted],
            "conflicts": [{"source": s, "reason": r} for s, r in plan.conflicts],
        }, indent=2, sort_keys=True))
        return
    prefix = "would " if dry_run else ""
    for item in plan.items:
        print(f"{prefix}{item['action']}: {item['file']} <- {item['source']}")
    for source, reason in plan.omitted:
        print(f"omitted: {source}: {reason}")
    for source, reason in plan.conflicts:
        print(f"conflict: {source}: {reason}")
    if not (plan.items or plan.omitted or plan.conflicts):
        print("Codex agents: nothing to publish" if not dry_run else "Codex agents: nothing to publish (dry run)")


def require_tomllib() -> None:
    if tomllib is None:
        version = sys.version.split()[0] if sys.version else "unknown"
        raise Refusal(
            f"Codex agent publication needs Python 3.11 or newer (tomllib is missing), "
            f"but the interpreter on PATH is Python {version} ({sys.executable}); "
            f"run solar client sync with a Python 3.11+ `python3`")


def scope_listing(workspace: Path, cfg: Config) -> dict:
    names = list_planet_entries(workspace)
    excluded = excluded_planet_map(cfg)
    planets = []
    for name in names or []:
        if name.startswith("."):
            continue
        scope = excluded.get(planet_key(name))
        if scope is not None:
            planets.append({"name": name, "status": f"excluded ({scope})"})
        else:
            try:
                if not os.path.isdir(workspace / "planets" / name):
                    continue
            except OSError:
                continue
            planets.append({"name": name, "status": "would read"})
    return {
        "enabled": cfg.enabled,
        "exclude_planets_global": sorted(cfg.global_exclude_planets),
        "exclude_planets_codex": sorted(cfg.exclude_planets),
        "exclude_agents": sorted(cfg.exclude_agents),
        "planets": planets,
    }


def print_scope(listing: dict) -> None:
    print(f"Codex agents: {'enabled' if listing['enabled'] else 'disabled'}")
    print("Planet scope (names only; no planet content is read by this listing):")
    if not listing["planets"]:
        print("  (no planets)")
    for planet in listing["planets"]:
        print(f"  {planet['name']}: {planet['status']}")
    print("exclude_planets (global): " + (", ".join(listing["exclude_planets_global"]) or "(none)"))
    print("exclude_planets (codex): " + (", ".join(listing["exclude_planets_codex"]) or "(none)"))
    print("exclude_agents: " + (", ".join(listing["exclude_agents"]) or "(none)"))


