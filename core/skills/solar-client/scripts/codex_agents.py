def cmd_exclude(workspace: Path, args) -> int:
    cfg = load_config(workspace)
    if args.action == "list":
        lines = [f"planet: {p}" for p in cfg.exclude_planets]
        lines += [f"agent: {a}" for a in cfg.exclude_agents]
        global_lines = [f"planet: {p} (global, applies to Codex agents too)"
                        for p in cfg.global_exclude_planets]
        for line in lines + global_lines:
            print(line)
        if not (lines or global_lines):
            print("(none)")
        return EXIT_OK
    target = args.target
    if target is None:
        raise Usage(f"exclude {args.action} requires <planet> or <planet>:<agent>")
    if ":" in target:
        match = IDENTITY_RE.fullmatch(target)
        if not match:
            raise Usage(f"invalid agent identity: {target!r}")
        key = agent_key(match.group(1), match.group(2))
        current = cfg.exclude_agents
        matches = lambda v: agent_key(*IDENTITY_RE.fullmatch(v).groups()) == key  # noqa: E731
        label = "agent"
    else:
        if not ID_RE.fullmatch(target) or target in (".", ".."):
            raise Usage(f"invalid planet name: {target!r}")
        current = cfg.exclude_planets
        matches = lambda v: planet_key(v) == planet_key(target)  # noqa: E731
        label = "planet"
    present = any(matches(v) for v in current)
    if args.action == "add":
        if present:
            print(f"OK: already excluded from Codex agents: {target}")
            return EXIT_OK
        current.append(target)
        write_config(workspace, cfg)
        print(f"OK: excluded {label} from Codex agents: {target}")
        return EXIT_OK
    if not present:
        print(f"OK: {label} was not excluded from Codex agents: {target}")
        return EXIT_OK
    current[:] = [v for v in current if not matches(v)]
    write_config(workspace, cfg)
    print(f"OK: removed {label} from Codex agent exclusions: {target}")
    return EXIT_OK


def cmd_preview(workspace: Path, args) -> int:
    cfg = load_config(workspace)
    if not args.contents:
        listing = scope_listing(workspace, cfg)
        if args.json:
            print(json.dumps(dict(listing, mode="scope"), indent=2, sort_keys=True))
        else:
            print_scope(listing)
            print("Scope only: no planet content was opened. Use --contents for the full plan.")
        return EXIT_OK
    require_tomllib()
    scan = scan_sources(workspace, cfg)
    cfd, afd = open_codex_dir(workspace, create=False)
    try:
        dest = read_dest(workspace, cfd, afd)
    finally:
        for fd in (afd, cfd):
            if fd is not None:
                os.close(fd)
    if scan.planets_missing and dest.manifest:
        raise Refusal("planets/ is missing but the manifest lists agents; refusing")
    plan = build_plan(scan, dest)
    if not args.json and not cfg.enabled:
        print("Codex agents are disabled; this is a dry run and nothing is written.")
    report(plan, as_json=args.json, dry_run=True, enabled=cfg.enabled)
    return EXIT_CONFLICT if plan.conflicts else EXIT_OK


def cmd_publish(workspace: Path, args) -> int:
    cfg = load_config(workspace)
    if not cfg.enabled:
        print("Codex agents: disabled (opt-in). Enable with: solar client sync codex-agents enable")
        return EXIT_OK
    require_tomllib()
    scan = scan_sources(workspace, cfg)
    cfd, afd = open_codex_dir(workspace, create=False)
    try:
        if afd is None:
            dest = read_dest(workspace, cfd, None)
            plan = build_plan(scan, dest)
            if plan.writes:
                for fd in (afd, cfd):
                    if fd is not None:
                        os.close(fd)
                cfd, afd = open_codex_dir(workspace, create=True)
        if afd is None:
            report(plan)
            return EXIT_CONFLICT if plan.conflicts else EXIT_OK
        if not acquire_lock(afd):
            print("ERROR: another Codex agent publication holds the lock; nothing was changed", file=sys.stderr)
            return EXIT_LOCK
        try:
            dest = read_dest(workspace, cfd, afd)
            if scan.planets_missing and dest.manifest:
                raise Refusal("planets/ is missing but the manifest lists agents; refusing")
            for name in dest.stale_tmp:
                try:
                    os.unlink(name, dir_fd=afd)
                except OSError:
                    pass
            if dest.stale_tmp:
                os.fsync(afd)
            plan = build_plan(scan, dest)
            apply_plan(plan, dest, afd)
        finally:
            try:
                fcntl.flock(afd, fcntl.LOCK_UN)
            except OSError:
                pass
    finally:
        for fd in (afd, cfd):
            if fd is not None:
                os.close(fd)
    report(plan)
    return EXIT_CONFLICT if plan.conflicts else EXIT_OK


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="codex_agents.py", description=__doc__.splitlines()[0])
    parser.add_argument("--workspace", required=True)
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("status")
    p.add_argument("--json", action="store_true")
    sub.add_parser("enable")
    sub.add_parser("disable")
    p = sub.add_parser("exclude")
    p.add_argument("action", choices=["add", "remove", "list"])
    p.add_argument("target", nargs="?")
    p = sub.add_parser("preview")
    p.add_argument("--contents", action="store_true")
    p.add_argument("--json", action="store_true")
    sub.add_parser("publish")
    return parser


COMMANDS = {
    "status": cmd_status, "enable": cmd_enable, "disable": cmd_disable,
    "exclude": cmd_exclude, "preview": cmd_preview, "publish": cmd_publish,
}


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    workspace = Path(args.workspace)
    try:
        return COMMANDS[args.cmd](workspace, args)
    except Usage as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return EXIT_USAGE
    except Refusal as exc:
        print(f"ERROR: {exc}. Nothing was changed.", file=sys.stderr)
        return EXIT_REFUSED
    except InjectedFailure as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"ERROR: Codex agent publication failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
